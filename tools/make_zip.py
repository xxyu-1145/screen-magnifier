"""Build the distributable archive: the executable plus a Chinese readme.

The executable is self-contained, so the archive is only two files. What it
cannot carry is the part a recipient actually needs: that Windows will warn
about an unsigned program they downloaded, what the default hotkeys are, and
where the program writes its settings.

Run from the project root:  python tools/make_zip.py dist/ScreenMagnifier.exe
"""

from __future__ import annotations

import sys
import zipfile
from pathlib import Path

VERSION = "1.0.1"
APP_NAME = "ScreenMagnifier"
README_NAME = "README.txt"

README = """\
屏幕放大镜 ScreenMagnifier {version}
================================================================

在屏幕上框选一块区域，用 1 到 10 倍实时放大，显示在一个置顶窗口里。
放大窗口可以设为"鼠标穿透"，此时它完全不接收鼠标，底下的游戏和程序照常操作。

----------------------------------------------------------------
怎么运行
----------------------------------------------------------------
1. 先把压缩包解压到任意文件夹（不要在压缩包里直接双击运行）。
2. 双击 ScreenMagnifier.exe。不需要安装。

本程序不需要安装任何运行库，只用 Windows 10/11 自带的系统组件。

如果 Windows 弹出蓝色的"Windows 已保护你的电脑"：
    这是 SmartScreen 对"从网上下载的、没有数字签名的程序"的默认提示，
    不是病毒警告。点"更多信息"，再点"仍要运行"即可。
    （不做数字签名是因为签名需要购买代码签名证书。）

启动后不会出现主界面：程序缩到任务栏右下角的通知区域，同时打开一个设置窗口。
按 Ctrl+Alt+M 开始放大。

----------------------------------------------------------------
默认快捷键
----------------------------------------------------------------
Ctrl+Alt+M           开启 / 关闭放大
Ctrl+Alt+P           切换鼠标穿透
Ctrl+Alt+S           切换选区形状（矩形 → 圆形 → 椭圆 → 圆角矩形）
Ctrl+Alt++ / -       放大 / 缩小
                     档位 1, 1.25, 1.5, 2, 2.5, 3, 4, 5, 6, 8, 10
Ctrl+Alt+1..4        跳到预设倍率（2x / 4x / 8x / 10x）
Ctrl+Alt+方向键       调整放大窗口大小
Ctrl+Alt+R           把选区重置到屏幕中央
Ctrl+Alt+C           把放大窗口拉回屏幕中央
Ctrl+Alt+Q           退出

所有快捷键都能改：在设置窗口里点一下对应的输入框，然后按下新的组合键，Esc 取消。
组合键必须带 Ctrl / Alt / Shift / Win 中至少一个（F1~F12 这类功能键可以单按）。
只按一个字母不会有反应，输入框会提示需要配合修饰键——这样不会把那个按键
在别的程序里占掉。另外，本程序已经占用的组合键也能改到别的功能上：点输入框的
时候它会先把这些按键让出来，所以按 Ctrl+Alt+M 不会被"开启/关闭放大"抢走。
（PrintScreen 和键盘上的音量、多媒体按键由系统先截走，输入框收不到，无法设置。）

鼠标按键也能设成快捷键：点一下输入框，再按鼠标上的键。右键、中键和两个侧键
都可以，可以单独用，也可以配合 Ctrl / Alt / Shift / Win；左键不行——点输入框
用的就是左键。有两点要注意：
    1. 设好之后这个键就归本程序了，不再传给下面的窗口。比如把中键设成快捷键，
       全系统的中键拖动都会失效。想还回去，就在输入框里给它换一个键。
    2. 这类快捷键靠低级鼠标钩子生效（系统本身不支持鼠标快捷键）。如果打开了
       "严格兼容模式"，钩子会被拒绝，快捷键就不起作用，状态栏会说明原因。

----------------------------------------------------------------
常用操作
----------------------------------------------------------------
框选区域
    设置窗口里点"框选区域…"，拖动鼠标框出一块区域。
    在选区内拖动可以移动它，拖边缘可以缩放；底部有"确定 / 取消"按钮，
    在选区内双击或者按 Enter 也能确定，Esc 取消。
    鼠标指针会提示当前位置是移动、缩放还是新建。

鼠标穿透
    按 Ctrl+Alt+P 后，放大窗口不再接收鼠标，点击会落到下面的程序上。
    要恢复操作：再按一次 Ctrl+Alt+P，或者把鼠标移到放大窗口边缘停留 0.5 秒，
    窗口会亮起边框并恢复可操作。

放大窗口大小
    拖窗口边缘；或 Ctrl+Alt+方向键；或在设置窗口里直接输入宽高，
    也可以拖设置窗口里"放大窗口"那一栏的拖动条。
    不管用哪种方式，改变大小的时候窗口中心是固定的——它是就地放大
    缩小，不会往一边跑。窗口跑偏了按 Ctrl+Alt+C 拉回屏幕中央。
    最小 120×120，最大不超过当前屏幕分辨率。

    改窗口大小只改变"看见多少"，不改变放大倍数：倍数是多少，屏幕上的
    像素就放多大，永远一致。窗口比"选区×倍数"大，就多看一块周围的屏幕；
    比它小，就只显示选区中间的一部分。窗口的形状就是你选的形状：窗口
    变小，圆形、椭圆也跟着变小，不会变成矩形（形状之外是透明的）。
    想要画面更大或更小，改倍率；想让整个选区正好铺满窗口，点"适配选区"。
    出厂设置里窗口就是"320×240 选区 × 4 倍 = 1280×960"。

语言 / 恢复默认
    设置窗口右上角有 中文 / English 切换，以及"恢复默认"。

保存多个选区
    设置窗口"选区形状"那一栏下面有一排数字按钮 1 2 3 4，可以存四个选区。
    点其中一个就把那个选区调出来；调好位置之后点"保存选区"，当前选区
    就存进亮着的那个按钮里。亮着的按钮就是下次"保存选区"要写进去的
    位置，重启之后仍然记得。四个按钮出厂时都是默认选区，所以点哪一个
    都会有反应。

自定义预设倍率
    设置窗口"放大倍率"那一栏，四个倍率按钮（2x / 4x / 8x / 10x）下面
    各有一个输入框，里面的数字就是这个预设的倍率。点按钮或按
    Ctrl+Alt+1..4 都会跳到那个倍率。想改就直接在框里输入，比如把 2x
    改成 5x，输入 5 即可；范围是 1 到 10 倍，超出会自动收到最近的边界。

----------------------------------------------------------------
没反应的时候，先看这几条
----------------------------------------------------------------
设置窗口最下面那一行状态栏是排查的起点，它会说明程序认为自己在
做什么、用的是什么捕获方式。请对照下面几条：

1. 按了 Ctrl+Alt+M，但没有出现放大窗口
   * 状态栏里如果出现"……已由本程序接管"，说明这个组合键原本被别的
     程序占用（QQ、微信、输入法、显卡和音频的驱动工具都很常抢这一类
     组合键），程序已经改用键盘钩子把它接管过来，此时按它应该有效。
     但接管意味着那个程序收不到这个键了——如果你不想这样，换一个组合
     键即可。
   * 如果你打开了设置里的"严格兼容模式"，程序就不会接管被占用的组合
     键，状态栏只会写"……已被其他程序占用"。此时要么关掉严格兼容模式，
     要么点设置窗口里对应的输入框换一个组合键；也可以完全不用快捷键，
     直接点设置窗口左下角的"开启放大"按钮。
   * 状态栏里如果出现"捕获丢失"，说明显卡暂时抓不到画面，程序会自
     动重试；如果"捕获"后面写的是 GDI，说明它已经退回到备用方式，
     画面会慢一些，但能用。

2. Windows 弹出"Windows 已保护你的电脑"
   见上面"怎么运行"第 3 条。

3. 放大窗口是全黑的
   把设置窗口里"渲染"一栏的"捕获时排除自身"取消勾选，再关掉放大
   重新开启。默认状态下不应该出现全黑，如果这样能恢复，请告诉我。

4. 全屏游戏里没有画面
   独占全屏的游戏无法被捕获。把游戏改成"无边框窗口"模式即可。

5. 还是不行
   把设置窗口底部那一整行状态栏的文字发回给我。那一行里包含了判
   断所需的信息（状态、选区、输出尺寸、帧率、捕获方式，以及出错时
   的原因），有它就能定位。

----------------------------------------------------------------
系统要求
----------------------------------------------------------------
Windows 10 或 Windows 11，64 位。
显卡需要支持 DirectX 11（2010 年以后的显卡基本都支持）。

----------------------------------------------------------------
隐私与安全
----------------------------------------------------------------
* 不联网，不发送任何数据。
* 不注入、不读写其他进程，不安装驱动或系统服务。
* 以普通用户权限运行，不需要管理员权限。
* 唯一写入的文件是配置：%APPDATA%\\Magnifier\\config.json

----------------------------------------------------------------
卸载
----------------------------------------------------------------
删除 ScreenMagnifier.exe，再删除 %APPDATA%\\Magnifier 文件夹即可。
没有注册表项、没有系统服务、没有驱动残留。

----------------------------------------------------------------
已知限制
----------------------------------------------------------------
* 独占全屏游戏、受保护视频、部分反作弊保护的画面可能无法被捕获。
  这种情况下程序会在设置窗口的状态栏里说明原因，不会尝试绕过。
* 放大窗口尺寸受当前桌面分辨率限制。
"""


def main(argv: list[str]) -> int:
    exe = Path(argv[1] if len(argv) > 1 else f"dist/{APP_NAME}.exe")
    if not exe.exists():
        raise SystemExit(f"{exe} not found; run ./build.sh package first")

    archive = exe.parent / f"{APP_NAME}-{VERSION}.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as bundle:
        bundle.write(exe, f"{APP_NAME}.exe")
        # ASCII file names keep the archive readable by any tool; the content
        # is what the recipient actually reads.
        # A UTF-8 BOM, so the Chinese renders in any editor the recipient
        # happens to open it with rather than only in ones that sniff encoding.
        bundle.writestr(README_NAME, "\ufeff" + README.format(version=VERSION))

    size_mb = archive.stat().st_size / (1024 * 1024)
    print(f"wrote {archive}  ({size_mb:.2f} MB)")
    print(f"  contains {APP_NAME}.exe and {README_NAME}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
